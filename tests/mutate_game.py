def run_one(mutation, vice):
    """One mutation in its own copy: the test's result."""
    name, file, text, replacement, must_fail = mutation
    with tempfile.TemporaryDirectory() as folder:
        copy = Path(folder)
        for part in ("game/src", "game/assets", "tests"):
            shutil.copytree(PROJECT / part, copy / part)
        (copy / "game/build").mkdir()
        (copy / "evidence").mkdir()
        source = copy / file
        content = source.read_text(encoding="utf-8")
        if content.count(text) != 1:
            raise SystemExit(f"{name}: the text is not there once")
        source.write_text(content.replace(text, replacement),
                          encoding="utf-8")
        built = subprocess.run(
            [ASSEMBLER, "--cbm-prg", "-Wall", "-Werror",
             "--vice-labels-numeric", "-l", "game/build/dreadcastle.lbl",
             "-o", "game/build/dreadcastle.prg", "game/src/main.asm"],
            cwd=copy, capture_output=True, text=True)
        if built.returncode:
            raise SystemExit(f"{name}: 64tass failed\n{built.stdout}")
        run = subprocess.run(
            [sys.executable, "tests/verify_game.py", "--vice", vice,
             "--stop-at", must_fail],
            cwd=copy, capture_output=True, text=True)
        written = copy / "evidence/game-test.json"
        if not written.exists():    # the test itself broke:
            print("MISSED " + name + " (the test broke)", flush=True)
            return {"mutation": name, "file": file,   # not caught
                    "test_result": "BROKEN", "must_fail": must_fail,
                    "failed_checks": [], "caught": False,
                    "error": run.stderr[-2000:]}
        report = json.loads(written.read_text(encoding="utf-8"))
    failed = [item["check"] for item in report["checks"]
              if not item["pass"]]
    caught = (run.returncode == 1 and
              any(check.startswith(must_fail) or must_fail in check
                  for check in failed))
    print(("CAUGHT " if caught else "MISSED ") + name, flush=True)
    return {"mutation": name, "file": file,
            "test_result": report["result"], "must_fail": must_fail,
            "failed_checks": failed, "caught": caught}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vice", default=shutil.which("x64sc") or "x64sc")
    parser.add_argument("--jobs", type=int, default=1)
    parser.add_argument("--only", default=None)
    args = parser.parse_args()
    chosen = [m for m in MUTATIONS
              if args.only is None or args.only in m[0]]
    for name, file, text, _, _ in chosen:      # all there, first
        found = (PROJECT / file).read_text(encoding="utf-8").count(text)
        if found != 1:
            raise SystemExit(f"{name}: the text is there {found} times")
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = list(pool.map(lambda m: run_one(m, args.vice), chosen))
    if args.only is None:
        with open(REPORT, "w", encoding="utf-8", newline="\n") as out:
            out.write(json.dumps({"mutations": results}, indent=2)
                      + "\n")
    missed = [r["mutation"] for r in results if not r["caught"]]
    print(f"{len(results) - len(missed)} of {len(results)} mutations "
          "caught" + ("" if args.only else
                      f"; report {REPORT.relative_to(PROJECT)}"))
    for name in missed:
        print("  missed:", name)
    return 1 if missed else 0


if __name__ == "__main__":
    sys.exit(main())
