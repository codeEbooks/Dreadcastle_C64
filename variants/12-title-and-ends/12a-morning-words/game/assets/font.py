GLYPH_ORDER = (list(" 0123456789ABCDEFGHIKLMNOPRSTUVWYZ/-")
               + list(ICONS) + list(BARS) + list(MORE))


def code(name):
    """Character code of a glyph, icon or bar."""
    return GLYPH_ORDER.index(name)


def rows(name):
    for table in (GLYPHS, ICONS, BARS, MORE):
        if name in table:
            return table[name]
    raise KeyError(name)


def glyph_bytes(name):
    data = []
    for line in rows(name):
        if len(line) != 8 or set(line) - {"#", "."}:
            raise ValueError(f"glyph {name!r}: bad row {line!r}")
        data.append(int(line.replace("#", "1").replace(".", "0"), 2))
    if len(data) != 8:
        raise ValueError(f"glyph {name!r}: {len(data)} rows")
    return bytes(data)
